-- Profiles use Supabase Auth IDs. Never store passwords in public tables.
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null check (length(trim(first_name)) > 0),
  last_name text not null check (length(trim(last_name)) > 0),
  email text,
  avatar text,
  unit_house_lot_number text not null default '',
  subdivision_village text not null default '',
  barangay text not null default '',
  municipality text not null default '',
  latitude double precision,
  longitude double precision,
  constraint profile_pin_pair check ((latitude is null) = (longitude is null)),
  constraint profile_latitude check (latitude between -90 and 90),
  constraint profile_longitude check (longitude between -180 and 180)
);

create table public.food_items (
  id bigint generated by default as identity primary key,
  photo text not null,
  name text not null check (length(trim(name)) > 0),
  price numeric(12,2) not null check (price >= 0),
  category text not null default ''
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references public.profiles(id),
  unit_house_lot_number text not null check (length(trim(unit_house_lot_number)) > 0),
  subdivision_village text not null default '',
  barangay text not null check (length(trim(barangay)) > 0),
  municipality text not null check (length(trim(municipality)) > 0),
  latitude double precision,
  longitude double precision,
  shipping_price numeric(12,2) not null check (shipping_price >= 0),
  tip_price numeric(12,2) not null default 0 check (tip_price >= 0),
  total_price numeric(12,2) not null check (total_price >= 0),
  created_at timestamptz not null default now(),
  constraint order_pin_pair check ((latitude is null) = (longitude is null)),
  constraint order_latitude check (latitude between -90 and 90),
  constraint order_longitude check (longitude between -180 and 180)
);

-- A relational order line preserves the item ID, its quantity, and its price
-- at checkout even if the catalog price changes later.
create table public.order_items (
  order_id uuid not null references public.orders(id) on delete cascade,
  item_id bigint not null references public.food_items(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  primary key (order_id, item_id)
);

create index orders_account_created_idx on public.orders(account_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.food_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "read own profile" on public.profiles for select to authenticated
  using (id = (select auth.uid()));
create policy "insert own profile" on public.profiles for insert to authenticated
  with check (id = (select auth.uid()));
create policy "update own profile" on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));
create policy "read food items" on public.food_items for select to authenticated
  using (true);
create policy "read own orders" on public.orders for select to authenticated
  using (account_id = (select auth.uid()));
create policy "read own order items" on public.order_items for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id
    and o.account_id = (select auth.uid())));
